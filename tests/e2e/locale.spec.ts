import { expect, test } from "@playwright/test";

test.use({ locale: "en-US" });

test("fresh English learning completes with bilingual draft and experiment continuity", async ({ page, isMobile }) => {
  const apiRequests: string[] = [];
  page.on("request", (request) => { if (new URL(request.url()).pathname.startsWith("/api/")) apiRequests.push(request.url()); });
  await page.goto("/");
  await expect(page.locator("html")).toHaveAttribute("lang", "en");
  await expect(page).toHaveTitle("Understanding Lab");
  expect(await page.evaluate(() => localStorage.getItem("understanding-lab:ui-locale"))).toBeNull();
  await page.getByRole("button", { name: "Start learning", exact: true }).click();
  await page.getByLabel("Your explanation", { exact: true }).fill("A flexible model can fit noise, not just the signal.");
  await page.getByLabel("My notes (up to 8000 characters)").fill("Compare training with validation.");
  const draft = await page.evaluate(() => localStorage.getItem("understanding-lab:v1:anonymous:current"));
  await page.getByLabel("Language / 语言").selectOption("zh-CN");
  await expect(page.getByLabel("我的解释", { exact: true })).toHaveValue("A flexible model can fit noise, not just the signal.");
  expect(await page.evaluate(() => localStorage.getItem("understanding-lab:v1:anonymous:current"))).toBe(draft);
  await page.reload();
  await expect(page.locator("html")).toHaveAttribute("lang", "zh-CN");
  await page.getByLabel("Language / 语言").selectOption("en");
  await expect(page.getByLabel("My notes (up to 8000 characters)")).toHaveValue("Compare training with validation.");
  await page.getByRole("button", { name: "Confirm this explanation" }).click();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: "Skip as unverified" }).click();
  await page.getByRole("button", { name: "Skip as unverified" }).click();
  await page.getByLabel("Your explanation", { exact: true }).fill("Validation error may rise even as training error falls.");
  await page.getByRole("button", { name: "Confirm this explanation" }).click();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByLabel("Polynomial degree").selectOption("8");
  await page.getByRole("button", { name: "Freeze current selection" }).click();
  await page.getByRole("button", { name: "Reveal final test result" }).click();
  const experiment = await page.evaluate(() => JSON.parse(localStorage.getItem("understanding-lab:v1:anonymous:current")!).exploration);
  await page.getByLabel("Language / 语言").selectOption("zh-CN");
  await expect(page.getByLabel("多项式阶数")).toHaveValue("8");
  await page.getByLabel("Language / 语言").selectOption("en");
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("understanding-lab:v1:anonymous:current")!).exploration)).toEqual(experiment);
  await page.getByRole("button", { name: "Record experiment observation" }).click();
  if (isMobile) await page.getByRole("button", { name: "Explanation", exact: true }).click();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByLabel("Your explanation", { exact: true }).fill("Generalization needs evidence beyond the training data.");
  await page.getByRole("button", { name: "Confirm this explanation" }).click();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByLabel("Your explanation", { exact: true }).fill("Repeated test-set selection leaks information into the choice.");
  await page.getByRole("button", { name: "Confirm this explanation" }).click();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Attempt summary" })).toBeVisible();
  await expect(page.getByText("A flexible model can fit noise, not just the signal.", { exact: true })).toBeVisible();
  await expect(page.getByText(/Clarify.*Unverified/)).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Attempt summary" })).toBeVisible();
  await expect(page.locator("html")).toHaveAttribute("lang", "en");
  if (isMobile) expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(apiRequests).toEqual([]);
});
